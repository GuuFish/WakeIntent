function event(id, at, role, content) {
  return { id, at, role, content };
}

function scenario(input) {
  const phase1 = input.phase1.map((content, index) =>
    event(`${input.id}-p1-${index + 1}`, `2026-10-01T0${index}:00:00+08:00`, index % 2 === 0 ? "user" : "assistant", content),
  );
  const phase3 = (input.phase3 ?? []).map((item, index) =>
    event(`${input.id}-p3-${index + 1}`, `2026-10-05T0${index}:00:00+08:00`, item.role ?? "user", item.content),
  );
  const tools = input.tools.map((tool, index) => ({
    queryKey: tool[0],
    description: tool[1],
    awayResults: tool[2] === null ? [] : [{
      id: `${input.id}-tool-${index + 1}-away`,
      content: tool[2],
      observedAt: "2026-10-03T10:00:00+08:00",
    }],
    returnResults: tool[3] === null ? [] : [{
      id: `${input.id}-tool-${index + 1}-return`,
      content: tool[3],
      observedAt: "2026-10-07T10:00:00+08:00",
    }],
  }));
  return {
    id: input.id,
    category: input.category,
    valueOpportunity: input.valueOpportunity,
    phase1,
    awayAt: "2026-10-03T10:00:00+08:00",
    phase3,
    returnAt: "2026-10-07T10:00:00+08:00",
    reentry: input.reentry,
    userState: input.userState ?? { proactiveContactAllowed: true, quiet: false },
    tools,
    expected: {
      awayActions: input.awayActions ?? ["lookup", "do_nothing"],
      reentryActions: input.reentryActions,
      experienceUse: input.experienceUse,
      notes: input.notes,
    },
  };
}

